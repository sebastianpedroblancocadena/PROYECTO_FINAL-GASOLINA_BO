class Utilidades:

    @staticmethod
    def fecha_actual():
        return datetime.now().strftime("%Y-%m-%d %H:%M:%S")

    @staticmethod
    def limpiar():
        print("\n" * 3)

    @staticmethod
    def pausa():
        input("\nPresiona ENTER para continuar...")

    @staticmethod
    def animacion(mensaje, segundos=1.0):
        print("\n" + mensaje)
        pasos = 20

        for i in range(pasos + 1):
            porcentaje = int((i / pasos) * 100)
            barra = "#" * i + "-" * (pasos - i)
            print(
                "\r[" + barra + "] " + str(porcentaje) + "%",
                end=""
            )
            time.sleep(segundos / pasos)

        print()

    @staticmethod
    def guardar_json(archivo, datos):
        try:
            with open(archivo, "w", encoding="utf-8") as file:
                json.dump(
                    datos,
                    file,
                    indent=4,
                    ensure_ascii=False
                )
        except Exception as error:
            print("\nError guardando archivo:", error)

    @staticmethod
    def leer_json(archivo):
        if not os.path.exists(archivo):
            return []

        try:
            with open(archivo, "r", encoding="utf-8") as file:
                return json.load(file)
        except Exception:
            return []


