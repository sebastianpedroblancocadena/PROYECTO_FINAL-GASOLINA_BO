class BaseDatos:

    def __init__(self, archivo):
        self.archivo = archivo
        self.conexion = sqlite3.connect(self.archivo)
        self.conexion.execute("PRAGMA foreign_keys = ON")
        self.crear_tablas()

    # --------------------------------------------------------
    # CREAR TABLAS
    # --------------------------------------------------------

    def crear_tablas(self):
        cursor = self.conexion.cursor()

        cursor.execute("""
            CREATE TABLE IF NOT EXISTS camiones (
                id INTEGER PRIMARY KEY AUTOINCREMENT,
                placa TEXT UNIQUE NOT NULL,
                conductor TEXT,
                capacidad REAL,
                estado TEXT,
                fecha_registro TEXT
            )
        """)

        cursor.execute("""
            CREATE TABLE IF NOT EXISTS envios (
                id INTEGER PRIMARY KEY AUTOINCREMENT,
                camion_id INTEGER NOT NULL,
                origen TEXT NOT NULL,
                destino TEXT NOT NULL,
                volumen_inicial REAL,
                volumen_actual REAL,
                estado TEXT,
                fecha TEXT,
                FOREIGN KEY(camion_id) REFERENCES camiones(id)
            )
        """)

        cursor.execute("""
            CREATE TABLE IF NOT EXISTS sensores (
                id INTEGER PRIMARY KEY AUTOINCREMENT,
                envio_id INTEGER NOT NULL,
                camion_id INTEGER NOT NULL,
                volumen REAL,
                densidad REAL,
                temperatura REAL,
                latitud REAL,
                longitud REAL,
                firma TEXT,
                fecha TEXT,
                FOREIGN KEY(envio_id) REFERENCES envios(id),
                FOREIGN KEY(camion_id) REFERENCES camiones(id)
            )
        """)

        cursor.execute("""
            CREATE TABLE IF NOT EXISTS eventos (
                id INTEGER PRIMARY KEY AUTOINCREMENT,
                envio_id INTEGER,
                tipo TEXT,
                descripcion TEXT,
                severidad TEXT,
                fecha TEXT,
                FOREIGN KEY(envio_id) REFERENCES envios(id)
            )
        """)

        cursor.execute("""
            CREATE TABLE IF NOT EXISTS bloques (
                id INTEGER PRIMARY KEY AUTOINCREMENT,
                numero INTEGER UNIQUE,
                evento TEXT,
                datos TEXT,
                hash_anterior TEXT,
                hash_actual TEXT,
                fecha TEXT
            )
        """)

        self.conexion.commit()

    # --------------------------------------------------------
    # CAMIONES
    # --------------------------------------------------------

    def insertar_camion(self, placa, conductor, capacidad):
        cursor = self.conexion.cursor()

        try:
            cursor.execute("""
                INSERT INTO camiones
                (placa, conductor, capacidad, estado, fecha_registro)
                VALUES (?, ?, ?, ?, ?)
            """, (
                placa,
                conductor,
                capacidad,
                "DISPONIBLE",
                Utilidades.fecha_actual()
            ))
            self.conexion.commit()
            return cursor.lastrowid

        except sqlite3.IntegrityError:
            cursor.execute(
                "SELECT id FROM camiones WHERE placa = ?",
                (placa,)
            )
            resultado = cursor.fetchone()
            return resultado[0]

    # --------------------------------------------------------
    # ENVIOS
    # --------------------------------------------------------

    def insertar_envio(self, envio):
        camion_id = self.obtener_camion_id(envio.camion)
        cursor = self.conexion.cursor()

        cursor.execute("""
            INSERT INTO envios
            (camion_id, origen, destino, volumen_inicial,
             volumen_actual, estado, fecha)
            VALUES (?, ?, ?, ?, ?, ?, ?)
        """, (
            camion_id,
            envio.origen,
            envio.destino,
            envio.volumen_inicial,
            envio.volumen_actual,
            envio.estado,
            envio.fecha
        ))

        self.conexion.commit()
        return cursor.lastrowid

    def actualizar_volumen_envio(self, envio_id, volumen):
        cursor = self.conexion.cursor()
        cursor.execute("""
            UPDATE envios
            SET volumen_actual = ?
            WHERE id = ?
        """, (volumen, envio_id))
        self.conexion.commit()

    def actualizar_estado_envio(self, envio_id, estado):
        cursor = self.conexion.cursor()
        cursor.execute("""
            UPDATE envios
            SET estado = ?
            WHERE id = ?
        """, (estado, envio_id))
        self.conexion.commit()

    # --------------------------------------------------------
    # OBTENER CAMION
    # --------------------------------------------------------

    def obtener_camion_id(self, placa):
        cursor = self.conexion.cursor()
        cursor.execute(
            "SELECT id FROM camiones WHERE placa = ?",
            (placa,)
        )
        resultado = cursor.fetchone()

        if resultado:
            return resultado[0]

        return self.insertar_camion(
            placa,
            "Conductor Demo",
            20000
        )

    # --------------------------------------------------------
    # SENSORES
    # --------------------------------------------------------

    def insertar_sensor(self, lectura):
        camion_id = self.obtener_camion_id(lectura["camion"])
        cursor = self.conexion.cursor()

        cursor.execute("""
            INSERT INTO sensores
            (envio_id, camion_id, volumen, densidad, temperatura,
             latitud, longitud, firma, fecha)
            VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?)
        """, (
            lectura["envio_id"],
            camion_id,
            lectura["volumen"],
            lectura["densidad"],
            lectura["temperatura"],
            lectura["latitud"],
            lectura["longitud"],
            lectura["firma"],
            lectura["fecha"]
        ))

        self.conexion.commit()

    # --------------------------------------------------------
    # EVENTOS
    # --------------------------------------------------------

    def insertar_evento(self, envio_id, tipo, descripcion, severidad):
        cursor = self.conexion.cursor()

        cursor.execute("""
            INSERT INTO eventos
            (envio_id, tipo, descripcion, severidad, fecha)
            VALUES (?, ?, ?, ?, ?)
        """, (
            envio_id,
            tipo,
            descripcion,
            severidad,
            Utilidades.fecha_actual()
        ))

        self.conexion.commit()
        return cursor.lastrowid

    # --------------------------------------------------------
    # BLOCKCHAIN
    # --------------------------------------------------------

    def insertar_bloque(self, bloque):
        cursor = self.conexion.cursor()

        cursor.execute("""
            INSERT INTO bloques
            (numero, evento, datos, hash_anterior, hash_actual, fecha)
            VALUES (?, ?, ?, ?, ?, ?)
        """, (
            bloque["numero"],
            bloque["evento"],
            json.dumps(bloque["datos"], sort_keys=True),
            bloque["hash_anterior"],
            bloque["hash_actual"],
            bloque["fecha"]
        ))

        self.conexion.commit()

    def obtener_ultimo_hash(self):
        cursor = self.conexion.cursor()
        cursor.execute("""
            SELECT hash_actual
            FROM bloques
            ORDER BY numero DESC
            LIMIT 1
        """)
        resultado = cursor.fetchone()
        return "GENESIS" if resultado is None else resultado[0]

    def obtener_numero_bloque(self):
        cursor = self.conexion.cursor()
        cursor.execute("SELECT MAX(numero) FROM bloques")
        resultado = cursor.fetchone()
        return 0 if resultado[0] is None else resultado[0] + 1

    # --------------------------------------------------------
    # CONSULTAS
    # --------------------------------------------------------

    def contar_bloques(self):
        return self.conexion.execute(
            "SELECT COUNT(*) FROM bloques"
        ).fetchone()[0]

    def contar_sensores(self):
        return self.conexion.execute(
            "SELECT COUNT(*) FROM sensores"
        ).fetchone()[0]

    def contar_eventos(self):
        return self.conexion.execute(
            "SELECT COUNT(*) FROM eventos"
        ).fetchone()[0]

    def contar_envios(self):
        return self.conexion.execute(
            "SELECT COUNT(*) FROM envios"
        ).fetchone()[0]

    def contar_alertas(self):
        return self.conexion.execute("""
            SELECT COUNT(*) FROM eventos
            WHERE severidad = 'CRITICA'
        """).fetchone()[0]

    def obtener_envios(self):
        cursor = self.conexion.cursor()
        cursor.execute("""
            SELECT
                envios.id,
                camiones.placa,
                envios.origen,
                envios.destino,
                envios.volumen_inicial,
                envios.volumen_actual,
                envios.estado,
                envios.fecha
            FROM envios
            INNER JOIN camiones
                ON envios.camion_id = camiones.id
            ORDER BY envios.id DESC
        """)
        return cursor.fetchall()

    def obtener_sensores(self):
        cursor = self.conexion.cursor()
        cursor.execute("""
            SELECT
                id,
                envio_id,
                volumen,
                densidad,
                temperatura,
                latitud,
                longitud,
                firma,
                fecha
            FROM sensores
            ORDER BY id DESC
        """)
        return cursor.fetchall()

    def obtener_eventos(self):
        cursor = self.conexion.cursor()
        cursor.execute("""
            SELECT
                id,
                envio_id,
                tipo,
                descripcion,
                severidad,
                fecha
            FROM eventos
            ORDER BY id DESC
        """)
        return cursor.fetchall()

    def obtener_bloques(self):
        cursor = self.conexion.cursor()
        cursor.execute("""
            SELECT
                numero,
                evento,
                datos,
                hash_anterior,
                hash_actual,
                fecha
            FROM bloques
            ORDER BY numero ASC
        """)
        return cursor.fetchall()

    # --------------------------------------------------------
    # NUEVO: DATAFRAMES PARA GOOGLE COLAB
    # --------------------------------------------------------

    def obtener_dataframe(self, tabla):
        """Lee una tabla SQLite directamente como DataFrame de Pandas."""
        tablas_permitidas = {
            "camiones",
            "envios",
            "sensores",
            "eventos",
            "bloques"
        }

        if tabla not in tablas_permitidas:
            raise ValueError("Tabla no permitida")

        return pd.read_sql_query(
            f"SELECT * FROM {tabla}",
            self.conexion
        )

    def mostrar_tabla_pandas(self, tabla):
        """Muestra una tabla SQLite de forma visual en Google Colab."""
        try:
            df = self.obtener_dataframe(tabla)

            print("\n" + "=" * 100)
            print(f" TABLA SQLITE: {tabla.upper()} | PANDAS")
            print("=" * 100)

            if df.empty:
                print("\nLa tabla esta vacia.")
                return

            if display is not None:
                display(df)
            else:
                print(df.to_string(index=False))

            print(f"\nRegistros mostrados: {len(df)}")

        except Exception as error:
            print("Error mostrando la tabla:", error)

