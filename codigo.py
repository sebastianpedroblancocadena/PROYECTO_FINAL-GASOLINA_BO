class Blockchain:

    def __init__(self, base_datos):
        self.base_datos = base_datos
        self.archivo = BLOCKCHAIN_FILE

    def crear_bloque(self, evento, datos):
        numero = self.base_datos.obtener_numero_bloque()
        hash_anterior = self.base_datos.obtener_ultimo_hash()
        fecha = Utilidades.fecha_actual()

        informacion = {
            "numero": numero,
            "evento": evento,
            "datos": datos,
            "hash_anterior": hash_anterior,
            "fecha": fecha
        }

        contenido = json.dumps(informacion, sort_keys=True)
        hash_actual = hashlib.sha256(
            contenido.encode("utf-8")
        ).hexdigest()

        bloque = {
            "numero": numero,
            "evento": evento,
            "datos": datos,
            "hash_anterior": hash_anterior,
            "hash_actual": hash_actual,
            "fecha": fecha
        }

        self.base_datos.insertar_bloque(bloque)
        self.exportar_json()
        return bloque

    def exportar_json(self):
        bloques_db = self.base_datos.obtener_bloques()
        bloques = []

        for bloque in bloques_db:
            bloques.append({
                "numero": bloque[0],
                "evento": bloque[1],
                "datos": json.loads(bloque[2]),
                "hash_anterior": bloque[3],
                "hash_actual": bloque[4],
                "fecha": bloque[5]
            })

        Utilidades.guardar_json(self.archivo, bloques)

    def mostrar(self):
        bloques = self.base_datos.obtener_bloques()

        print("\n")
        print("=" * 80)
        print(" BLOCKCHAIN")
        print("=" * 80)

        if not bloques:
            print("\nBlockchain vacia.")
            return

        for bloque in bloques:
            print("\nBloque:", bloque[0])
            print("Evento:", bloque[1])
            print("Hash anterior:", bloque[3][:30] + "...")
            print("Hash actual:", bloque[4][:30] + "...")
            print("Fecha:", bloque[5])
            print("-" * 80)

    def verificar_integridad(self):
        bloques = self.base_datos.obtener_bloques()

        if not bloques:
            print("\nBlockchain vacia.")
            return True

        hash_anterior_esperado = "GENESIS"
        correcto = True

        for bloque in bloques:
            numero = bloque[0]
            evento = bloque[1]
            datos = json.loads(bloque[2])
            hash_anterior = bloque[3]
            hash_actual = bloque[4]
            fecha = bloque[5]

            informacion = {
                "numero": numero,
                "evento": evento,
                "datos": datos,
                "hash_anterior": hash_anterior,
                "fecha": fecha
            }

            contenido = json.dumps(informacion, sort_keys=True)
            hash_calculado = hashlib.sha256(
                contenido.encode("utf-8")
            ).hexdigest()

            if hash_anterior != hash_anterior_esperado:
                correcto = False

            if hash_calculado != hash_actual:
                correcto = False

            hash_anterior_esperado = hash_actual

        print("\n")
        print("=" * 70)
        print(" VERIFICACION BLOCKCHAIN")
        print("=" * 70)

        if correcto:
            print("\n[OK] Blockchain integra.")
            print("[OK] Hashes correctos.")
            print("[OK] Cadena sin alteraciones.")
        else:
            print("\n[ERROR] Blockchain alterada.")
            print("[ERROR] Se detecto inconsistencia.")

        return correcto


