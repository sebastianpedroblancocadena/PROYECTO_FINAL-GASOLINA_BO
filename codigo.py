class Seguridad:

    # Simulacion educativa de una clave almacenada en hardware seguro.
    CLAVE_HSM = "HSM_FUELCHAIN_YPFB_ANH"

    @staticmethod
    def generar_firma(datos):
        contenido = json.dumps(datos, sort_keys=True)
        contenido += Seguridad.CLAVE_HSM
        return hashlib.sha256(
            contenido.encode("utf-8")
        ).hexdigest()

    @staticmethod
    def verificar_firma(datos, firma):
        firma_correcta = Seguridad.generar_firma(datos)
        return firma_correcta == firma


